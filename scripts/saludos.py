""" ejemplo del uso del for"""
lista = ['David', 'Felipe', 'Jorge', 'Jennifer', 'Santiago', 'Saray']

for i in lista: # podemos usar listas
    print(f'Hola {i} ')
print('-------------------')
for i in range(1,5,1): # también podemos usar range
    print(i)
print('-------------------')
for i in range(1,50,2): # también podemos usar range
    print(i)

